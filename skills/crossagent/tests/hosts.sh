# Sourced by run.sh: hosts.json, nicknames, generated worker definitions, and hostile
# folder, task and host names going through init, run, remote and the claude wrapper over
# a fake ssh (tests/fake-ssh) into a second home. Uses run.sh's t, dies, jcheck and $good.

H="$HOME/.config/crossagent/hosts.json"
cd "$T" || exit 1

echo "== hosts"
t "ca hosts lists both" sh -c "'$CA' hosts | grep -q '^mac .*this machine' && '$CA' hosts | grep -q '^pc .*ssh pc'"
nick() { [ "$("$CA" host "$1" 2>/dev/null)" = "$2" ]; }
for w in local mac "this mac" here laptop localhost "on my mac"; do t "'$w' means mac" nick "$w" mac; done
for w in pc "my pc" "on my pc" "Linux PC" "linux pc" remote ssh overseas "the other machine"; do t "'$w' means pc" nick "$w" pc; done
for w in "" both split all; do t "'$w' means all" nick "$w" all; done
dies "unknown nickname" "unknown host 'gpu'" "$CA" host gpu
t "CA_HERE=pc sees mac as a hub" sh -c "CA_HERE=pc '$CA' hosts | grep -q '^mac .*set this machine up'"
dies "and can't run there" "can't reach mac from pc" env CA_HERE=pc "$CA" run mac t1 -- true
t "no hosts.json: just this machine" sh -c "mv '$H' '$H.off'; '$CA' hosts > '$T/h0'; r=\$?; mv '$H.off' '$H'; [ \$r = 0 ] && [ \"\$(wc -l < '$T/h0')\" -eq 1 ] && grep -q '^mac ' '$T/h0'"
dies "no ssh hosts: remote has nowhere to go" "no ssh hosts are set up here" env HOME="$T/empty" "$CA" host remote

cp "$H" "$T/hosts.good"
python3 -I -c '
import json, sys
d = json.load(open(sys.argv[1]))
d["hosts"] += [{"id": "evil", "name": "x", "type": "ssh", "target": "-oProxyCommand=touch PWNED", "accent": "#000000"},
               {"id": "bad id", "name": "y", "type": "ssh", "target": "pc", "accent": "#000000"},
               {"id": "nl", "name": "z", "type": "ssh", "target": "a\nb", "accent": "#000000"}]
json.dump(d, open(sys.argv[1], "w"))' "$H"
"$CA" hosts > "$T/hevil" 2> "$T/hevil.err"
t "a target starting with - is skipped" grep -q "skipping host evil in hosts.json: bad ssh target" "$T/hevil.err"
t "a bad id is skipped" grep -q "bad or repeated id: 'bad id'" "$T/hevil.err"
t "a target with a newline is skipped" grep -q "skipping host nl" "$T/hevil.err"
t "the good hosts stay" test "$(wc -l < "$T/hevil")" -eq 2
cp "$T/hosts.good" "$H"; chmod 666 "$H"
"$CA" hosts > "$T/hopen" 2>&1
t "a hosts.json others can write is ignored" grep -q "ignoring .*hosts.json" "$T/hopen"
t "and then only this machine is known" test "$(grep -vc '^ca:' "$T/hopen")" -eq 1
chmod 600 "$H"

dies "hosts add refuses a bad id" "host ids are" "$CA" hosts add 'bad id' pc
dies "hosts add refuses a target starting with -" "bad ssh target" "$CA" hosts add evil '-oProxyCommand=touch PWNED'
dies "hosts add refuses this machine" "mac is this machine" "$CA" hosts add mac pc
dies "hosts add refuses an existing host" "already in hosts.json" "$CA" hosts add pc pc
dies "hosts add needs ssh to work" "can't reach 'nowhere'" "$CA" hosts add far nowhere
"$CA" hosts add box box Big Box > "$T/add" 2>&1
t "hosts add box" grep -q "added box (ssh box)" "$T/add"
t "the check used BatchMode and a timeout" grep -qF -- "-o BatchMode=yes -o ConnectTimeout=10 box true" "$FAKE_SSH_LOG"
t "hosts.json keeps the others and gets box" python3 -I -c '
import json, sys
h = json.load(open(sys.argv[1]))["hosts"]
ok = [x["id"] for x in h] == ["mac", "pc", "box"] and h[2] == {"accent": "#f2a65a", "id": "box", "name": "Big Box", "target": "box", "type": "ssh"} \
  and h[1]["accent"] == "#5fd39a"
sys.exit(0 if ok else 1)' "$H"
t "hosts.json is pretty and private" sh -c "grep -q '^  \"hosts\": \\[' '$H' && ls -l '$H' | grep -q '^-rw-------'"
t "box-worker was generated" sh -c "grep -q 'name: box-worker' '$HOME/.claude/agents/box-worker.md' && grep -q 'ca remote box <role>' '$HOME/.claude/agents/box-worker.md' && grep -q 'Big Box (crossagent host box' '$HOME/.claude/agents/box-worker.md'"
dies "two ssh hosts: remote is ambiguous" "could be any of the ssh hosts: pc, box" "$CA" host remote
t "'big box' means box" nick "big box" box
t "'on the box' means box" nick "on the box" box
dies "ca remote with an ambiguous word" "could be any of the ssh hosts" "$CA" remote overseas r1 --brief "$good"

printf 'old3\t~/old3\t~/crossagent/projects/old3\nold5\t~/old5\t~/old5\tca-old5\twatching\n' > "$HOME/.config/crossagent/projects"
(cd "$T" && mkdir -p reg && cd reg && CA_ROOT="$T/reg" "$CA" init mac) > /dev/null 2>&1
t "old 3 and 5 column registry rows survive as host pc" python3 -I -c '
import sys
r = [l.rstrip("\n").split("\t") for l in open(sys.argv[1])]
sys.exit(0 if ["old3", "~/old3", "pc", "~/crossagent/projects/old3", "", ""] in r and ["old5", "~/old5", "pc", "~/old5", "ca-old5", "watching"] in r and any(x[0] == "reg" and x[2] == "-" for x in r) else 1)' "$HOME/.config/crossagent/projects"

echo "== worker definitions"
A="$HOME/.claude/agents"
printf -- '---\nname: old-worker\n---\n<!-- generated by crossagent -->\n' > "$A/old-worker.md"
printf -- '---\nname: my-worker\n---\nmine\n' > "$A/my-worker.md"
printf -- '---\nname: pc-worker\n---\nYou are a thin proxy for a worker on the PC.\n' > "$A/pc-worker.md"
printf -- '---\nname: x-worker\n---\nnot ours\n' > "$A/zz-worker.md"
"$CA" __agents > "$T/ag" 2>&1
t "the old hand written pc-worker gets replaced" sh -c "grep -qxF '<!-- generated by crossagent -->' '$A/pc-worker.md' && grep -q 'ca remote pc <role>' '$A/pc-worker.md' && grep -q 'color: green' '$A/pc-worker.md'"
t "a marked worker for a gone host is removed" test ! -e "$A/old-worker.md"
t "an unmarked worker is never touched" sh -c "grep -q mine '$A/my-worker.md' && grep -q 'not ours' '$A/zz-worker.md'"
t "no mac-worker on the hub itself" test ! -e "$A/mac-worker.md"
t "generated workers are valid frontmatter" python3 -I -c '
import sys
for p in sys.argv[1:]:
    head = open(p).read().split("---\n")[1]
    for line in head.splitlines():
        k, _, v = line.partition(": ")
        if not k or not v or ": " in v or v[0] in "\"'"'"'`[{&*!|>%@":
            sys.exit(1)
' "$A/pc-worker.md" "$A/box-worker.md"
"$CA" hosts remove box > "$T/rm" 2>&1
t "hosts remove box" sh -c "grep -q 'removed box' '$T/rm' && ! grep -q '\"box\"' '$H'"
t "and its worker goes with it" test ! -e "$A/box-worker.md"
dies "hosts remove keeps this machine" "is this machine" "$CA" hosts remove mac
dies "hosts remove of an unknown host" "no host nope" "$CA" hosts remove nope
rm -f "$A/my-worker.md" "$A/zz-worker.md"

echo "== hostile names over ssh"
EVIL='my "proj" $(touch PWNED) `touch PWNED` '"'x'"' ü'
EP="$HOME/work/$EVIL"; mkdir -p "$EP"; echo hello > "$EP/hello.txt"
cd "$EP" || exit 1
"$CA" init pc > "$T/einit" 2>&1; rc=$?
t "init pc in a hostile folder" test "$rc" = 0
t "the project name is plain" grep -qxE 'name=[A-Za-z0-9._-]+' "$EP/.crossagent/project"
t "the skill got installed on pc" test -x "$FAKE_REMOTE/.claude/skills/crossagent/scripts/ca"
t "without the tests" test ! -e "$FAKE_REMOTE/.claude/skills/crossagent/tests"
t "pc knows itself and its hub" sh -c "grep -q '\"id\": \"pc\"' '$FAKE_REMOTE/.config/crossagent/hosts.json' && grep -qx mac '$FAKE_REMOTE/.config/crossagent/hubs'"
t "pc got a mac-worker that says it can't reach mac" sh -c "grep -q 'pc can not reach mac' '$FAKE_REMOTE/.claude/agents/mac-worker.md' && grep -q 'ca remote mac <role>' '$FAKE_REMOTE/.claude/agents/mac-worker.md'"
t "push landed in the same path on pc" cmp -s "$EP/hello.txt" "$FAKE_REMOTE/work/$EVIL/hello.txt"
t "the map has a section per host" python3 -I -c '
import sys
m = open(sys.argv[1]).read().splitlines()
sys.exit(0 if "<!-- ca:mac -->" in m and "<!-- ca:pc -->" in m and "## pc (Linux PC)" in m and "## mac (This Mac)" in m else 1)' "$EP/.crossagent/system-map.md"
t "the map got copied to pc" test -s "$FAKE_REMOTE/.config/crossagent/system-map.md"
t "ready line names both hosts" grep -qE '^ready: .*  mac=~/work/.*  pc=~/work/' "$T/einit"
ES=ca-my-proj-touch-pw

"$CA" run mac t1 -- 'echo hi from here' > /dev/null 2>&1
"$CA" wait mac t1 --timeout 20 > "$T/ew1" 2>&1; rc=$?
t "run and wait on mac" sh -c "[ $rc = 0 ] && grep -q 'hi from here' '$T/ew1' && grep -q '^$ES-mac-t1: done (exit 0)' '$T/ew1'"
"$CA" run pc t2 -- 'echo hi from there; pwd' > /dev/null 2>&1
"$CA" wait pc t2 --timeout 20 > "$T/ew2" 2>&1; rc=$?
t "run and wait on pc" sh -c "[ $rc = 0 ] && grep -q 'hi from there' '$T/ew2'"
t "it ran in the project folder on pc" grep -qxF "$FAKE_REMOTE/work/$EVIL" "$T/ew2"
t "logs from pc" sh -c "'$CA' logs pc t2 5 | grep -q 'hi from there'"
t "session names on pc" sh -c "TMUX_TMPDIR='$FAKE_REMOTE_TMUX' tmux ls -F '#S' | grep -qx '$ES-pc-t2'"
t "status covers both" sh -c "'$CA' status > '$T/est' && grep -q '$ES-mac-t1 .*done (exit 0)' '$T/est' && grep -q '$ES-pc-t2 .*done (exit 0)' '$T/est'"

printf '# Brief\n\n## Goal\nx\n## Context\nx\n## Files\nx\n## Task\nASK_PERMISSION\n## Verification\nx\n' > "$T/ask.md"
"$CA" remote pc w1 --brief "$T/ask.md" --model haiku --timeout 30 > "$T/er1" 2> "$T/ee1" &
W=$!
id=""; for _ in $(seq 150); do id="$(grep -o 'approval [a-f0-9]\{12\}' "$T/ee1" 2>/dev/null | head -1 | cut -d' ' -f2)"; [ -n "$id" ] && break; sleep 0.1; done
t "remote worker on pc asks for approval" test -n "$id"
t "ca remote answer over ssh" "$CA" remote answer pc "$id" allow
wait "$W"; rc=$?
t "remote worker on pc reports" sh -c "[ $rc = 0 ] && grep -q 'Permission: allow.' '$T/er1'"
t "worker session name on pc" sh -c "TMUX_TMPDIR='$FAKE_REMOTE_TMUX' tmux ls -F '#S' | grep -qx '$ES-pc-w1'"
t "worker state on pc is private" python3 -I -c '
import os, sys
d = os.path.join(sys.argv[1], ".crossagent", "remote")
sys.exit(0 if os.stat(d).st_mode & 0o777 == 0o700 and os.stat(os.path.join(d, "w1", "brief.md")).st_mode & 0o777 == 0o600 else 1)' "$FAKE_REMOTE/work/$EVIL"
t "pc's approvals and events are private" sh -c "ls -ld '$FAKE_REMOTE/.crossagent' '$FAKE_REMOTE/.crossagent/approvals' '$FAKE_REMOTE/.crossagent/events' | grep -vc '^drwx------' | grep -qx 0"
t "brief copy here" test -s "$EP/.crossagent/remote/pc-w1/brief-1.md"
"$CA" remote stop pc w1 > /dev/null 2>&1

dies "a task name with a newline" "task name must be" "$CA" run mac "$(printf 'ok\n$(touch PWNED)')" -- true
dies "a role with \$()" "task name must be" "$CA" remote pc 'r$(touch PWNED)' --brief "$good"
dies "a timeout with arithmetic in it" "whole number" "$CA" wait mac t1 --timeout 'a[$(touch PWNED)]'
dies "a timeout with a newline" "whole number" "$CA" wait mac t1 --timeout "$(printf '5\na[$(touch PWNED)]')"
dies "remote --timeout with arithmetic" "whole number" "$CA" remote wait pc w1 --timeout 'x[$(touch PWNED)]'
dies "log lines with a ;" "whole number" "$CA" logs mac t1 '1;touch PWNED'
dies "a request id with a newline" "12 hex chars" "$CA" remote answer pc "$(printf 'abcdef123456\n../x')" allow
dies "a model with a newline" "has to be one line" "$CA" remote pc w2 --brief "$good" --model "$(printf 'haiku\n$(touch PWNED)')"
t "a quoted host word is just unknown" sh -c "! '$CA' host '\$(touch PWNED)' 2>/dev/null"

D="$HOME/work/-dash proj"; mkdir -p "$D"; echo d > "$D/d.txt"
(cd "$D" && "$CA" init pc) > "$T/edash" 2>&1; rc=$?
t "a folder starting with - works" sh -c "[ $rc = 0 ] && cmp -s '$D/d.txt' '$FAKE_REMOTE/work/-dash proj/d.txt'"
O="$HOME/work/moved"; mkdir -p "$O/.crossagent"; echo m > "$O/m.txt"
printf 'name=moved\npc_dir=elsewhere/moved here\n' > "$O/.crossagent/project"
(cd "$O" && "$CA" portal push) > /dev/null 2>&1
t "pc_dir= still works as dir.pc=" cmp -s "$O/m.txt" "$FAKE_REMOTE/elsewhere/moved here/m.txt"
printf 'name=moved\ndir.pc=../../.ssh\n' > "$O/.crossagent/project"
dies "dir.pc= can't leave home" "has to be a folder under home" sh -c "cd '$O' && '$CA' portal push"
printf 'name=moved\ndir.pc=.ssh\n' > "$O/.crossagent/project"
dies "dir.pc= can't be hidden" "has to be a folder under home" sh -c "cd '$O' && '$CA' portal push"
t "nothing got written to ~/.ssh on pc" test ! -e "$FAKE_REMOTE/.ssh"

t "every ca ssh call shares ~/.crossagent/ssh" sh -c "! grep -v 'BatchMode=yes' '$FAKE_SSH_LOG' | grep -vqF 'ControlPath=~/.crossagent/ssh/%C'"
t "~/.crossagent/ssh is 0700 here" sh -c "ls -ld '$HOME/.crossagent/ssh' | grep -q '^drwx------'"

echo "== claude wrapper"
if script -q /dev/null true < /dev/null > /dev/null 2>&1; then
  : > "$T/tmux.log"; : > "$T/tmux.log.args"
  ( cd "$EP" && ANTHROPIC_EVIL='$(touch PWNED) `touch PWNED`' CLAUDE_CODE_NOTE="$(printf 'a\nANTHROPIC_GHOST=1')" \
      TMUX_LOG="$T/tmux.log" script -q /dev/null "$BASH" -c '
      tmux() { printf "%s\n" "$*" >> "$TMUX_LOG"; printf "[%s]\n" "$@" >> "$TMUX_LOG.args"; case "$1" in has-session|ls|show) return 1 ;; esac; return 0; }
      . "$1"; claude --model haiku' _ "$SKILL/scripts/claude-wrapper.sh" ) < /dev/null > /dev/null 2>&1
  t "wrapper names the session after this host" grep -q "^new-session -d -s $ES-mac-1 " "$T/tmux.log"
  t "wrapper runs claude through env" grep -q -- "-- env $HOME/.local/bin/claude --model haiku$" "$T/tmux.log"
  t "wrapper forwards values as they are" grep -qF -- '-e ANTHROPIC_EVIL=$(touch PWNED) `touch PWNED`' "$T/tmux.log"
  t "wrapper skips names that aren't set" sh -c "grep -q '^\[CLAUDE_CODE_NOTE=a$' '$T/tmux.log.args' && ! grep -q '^\[ANTHROPIC_GHOST=' '$T/tmux.log.args'"
else
  echo "skip  claude wrapper (no script(1) here)"
fi

t "nothing called PWNED anywhere" test -z "$(find "$T" -name PWNED 2>/dev/null)"
cd "$T" || exit 1
